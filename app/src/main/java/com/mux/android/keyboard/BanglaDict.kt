/** Small built-in Bangla word list. Used for suggestions and for auto-correcting phonetic spelling. */
object BanglaDict {
    private val words: List<String> = RAW.trim().split(Regex("\\s+")).distinct()
    private val set: HashSet<String> = HashSet(words)

    fun has(w: String): Boolean = set.contains(w)

    /** Up to [max] known words that start with [prefix] (and are longer than it). */
    fun complete(prefix: String, max: Int): List<String> {
        if (prefix.isEmpty()) return emptyList()
        val out = ArrayList<String>()
        for (w in words) {
            if (w.length > prefix.length && w.startsWith(prefix)) {
                out.add(w)
                if (out.size >= max) break
            }
        }
        return out
    }
}

